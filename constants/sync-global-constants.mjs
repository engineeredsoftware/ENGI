#!/usr/bin/env node
/**
 * Sync constants/global-constant-*.txt → constants/global-constants.ts
 * SSOT is the .txt file (value only). Generated TS is for runtime import (browser + Node).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = dirname(fileURLToPath(import.meta.url));
const files = readdirSync(dir)
  .filter((name) => /^global-constant-.+\.txt$/u.test(name))
  .sort();

const entries = files.map((file) => {
  const slug = file.replace(/^global-constant-/u, '').replace(/\.txt$/u, '');
  const exportName = `GLOBAL_CONSTANT_${slug.replace(/-/gu, '_').toUpperCase()}`;
  const value = readFileSync(join(dir, file), 'utf8').replace(/^\uFEFF/u, '').trim();
  if (!value) throw new Error(`${file} is empty`);
  if (value.includes('\n')) throw new Error(`${file} must be a single-line value`);
  return { file, exportName, value };
});

const body = entries
  .map(
    ({ file, exportName, value }) =>
      `/** SSOT: \`${file}\` */\nexport const ${exportName} = ${JSON.stringify(value)} as const;\n`,
  )
  .join('\n');

const out = `/**
 * Auto-generated by constants/sync-global-constants.mjs — do not edit by hand.
 * Source of truth: constants/global-constant-*.txt (one value per file).
 */
${body}`;

writeFileSync(join(dir, 'global-constants.ts'), out, 'utf8');
console.log(`Wrote global-constants.ts (${entries.length} constant(s))`);
